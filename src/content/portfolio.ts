/**
 * Portfolio, keyed by artist slug.
 *
 * Built from the pieces visible in each artist's own Instagram grid (screenshots in
 * /brief/instagram). Each entry is a request for the original photo as much as a
 * content record: `seenIn` tells the client which post to send.
 *
 * An entry renders only when ALL of these hold:
 *   - consentConfirmed is true (POPIA: the person in the photo agreed)
 *   - needsDecision is null
 *   - the original exists at media/<imageKey>.jpg (otherwise a TODO box shows in dev only)
 *
 * Alt text: style, subject, placement. Never repeat profanity or names that appear in the tattoo.
 */

type Draft = Omit<PortfolioEntry, 'imageKey' | 'consentConfirmed' | 'flags' | 'needsDecision' | 'healed' | 'kind'> &
  Partial<Pick<PortfolioEntry, 'flags' | 'needsDecision' | 'healed' | 'kind'>>;

